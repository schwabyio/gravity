  it('is a summary page and a page per collection, loading nothing and naming no folder', () => {
    const report = pages(
      run(collection('smoke', [result('list')]), collection('sessions', [result('create')]))
    )
    expect([...report.keys()]).toEqual(['summary.html', 'smoke.html', 'sessions.html'])
    for (const html of report.values()) {
      expect(html).toMatch(/^<!doctype html>/)
      expect(html).not.toMatch(/<(link|script|img|iframe)[^>]+(href|src)="?https?:/)
      // The version leads to the repo; where the run was is left out.
      expect(html).toContain(
        'Generated by <a href="https://github.com/schwabyio/gravity" target="_blank" rel="noopener noreferrer"'
      )
      expect(html).toContain('gta 1.2.3')
      expect(html).not.toContain('/work/shop')
      // Light or dark, with the system.
      expect(html).toContain('@media (prefers-color-scheme:dark)')
    }
  })

