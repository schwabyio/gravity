import { describe, expect, it } from 'vitest'
import type { ReceivedResponse, RunResult } from '@schwabyio/gravity-core'
import { htmlReport, runTime, type HtmlCollection, type HtmlRun } from './html.js'
import type { CollectionTally } from './report.js'

const response = (over: Partial<ReceivedResponse> = {}): ReceivedResponse => ({
  status: 200,
  statusText: 'OK',
  url: 'http://x/items',
  headers: [{ name: 'content-type', value: 'application/json' }],
  body: '{"id":1}',
  bodyKind: 'json',
  sizeBytes: 8,
  redirectCount: 0,
  timings: { startedAt: 0, ttfbMs: 5, totalMs: 7 },
  ...over
})

const result = (name: string, over: Partial<RunResult> = {}): RunResult => ({
  item: { path: 'collections/a.yml', name, seq: null },
  request: {
    method: 'GET',
    url: 'http://x/items',
    headers: [{ name: 'Accept', value: '*/*' }],
    body: null
  },
  response: response(),
  assertions: [{ name: 'Status is 200', status: 'pass' }],
  error: null,
  status: 'pass',
  durationMs: 9,
  ...over
})

const tallyOf = (passed: boolean, over: Partial<CollectionTally> = {}): CollectionTally => ({
  id: 'x',
  passed,
  durationMs: 10,
  steps: { total: 1, passed: passed ? 1 : 0, failed: passed ? 0 : 1, errored: 0, skipped: 0 },
  assertions: { total: 1, passed: passed ? 1 : 0, failed: passed ? 0 : 1 },
  skipped: false,
  error: null,
  problems: [],
  ...over
})

const collection = (
  id: string,
  results: RunResult[],
  passed = true,
  tally: Partial<CollectionTally> = {}
): HtmlCollection => ({
  id,
  file: `collections/${id}.yml`,
  startedAt: 0,
  durationMs: 10,
  tally: { ...tallyOf(passed, tally), id },
  outcome: {
    ok: true,
    summary: {
      total: results.length,
      passed: 0,
      failed: 0,
      errored: 0,
      skipped: 0,
      durationMs: 10,
      results
    },
    steps: results.map((_, index) => ({ index, line: index + 3 })),
    data: null
  }
})

const run = (...collections: HtmlCollection[]): HtmlRun => ({
  project: 'Shop',
  root: '/work/shop',
  version: '1.2.3',
  environment: 'staging',
  concurrency: 4,
  timeoutCollection: 60000,
  tags: [],
  bail: false,
  excluded: ['legacy'],
  untagged: 0,
  startedAt: 0,
  durationMs: 1234,
  collections
})

const pages = (r: HtmlRun) => new Map(htmlReport(r).map((p) => [p.path, p.html]))

/** The one page a run of these results writes for collection `a`. */
const pageFor = (...results: RunResult[]) => pages(run(collection('a', results))).get('a.html')!

